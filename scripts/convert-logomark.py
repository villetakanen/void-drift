"""One-off conversion of the ∅·Δ logomark from Noto Sans Math to SVG paths (D1).

The font is never committed or served. To redo the conversion:

    curl -L -o /tmp/NotoSansMath-Regular.ttf \
      https://github.com/notofonts/notofonts.github.io/raw/main/fonts/NotoSansMath/unhinted/ttf/NotoSansMath-Regular.ttf
    python3 scripts/convert-logomark.py /tmp/NotoSansMath-Regular.ttf

Requires fontTools (`pip install fonttools`); it is not a project dependency.
Writes apps/web/src/components/logomark.ts and apps/web/public/favicon.svg,
then formats both with Biome.
"""

import subprocess
import sys
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
# Gap between advance boxes, in font units (1000/em). Matches the former
# text logo: 0.2ch gap plus 0.1ch operator margin.
GAP = 180
GLYPHS = [("void", 0x2205), ("operator", 0x22C5), ("drift", 0x0394)]
FAVICON_BG = "#050510"  # --color-void
FAVICON_FG = "#eeff41"  # --color-acid-lime (brand)


def convert(font_path: str) -> None:
    font = TTFont(font_path)
    cmap = font.getBestCmap()
    glyphs = font.getGlyphSet()
    version = font["name"].getDebugName(5)

    placed = []
    x = 0
    for role, codepoint in GLYPHS:
        name = cmap[codepoint]
        bounds = BoundsPen(glyphs)
        glyphs[name].draw(bounds)
        placed.append((role, name, x, bounds.bounds))
        x += font["hmtx"][name][0] + GAP

    min_x = min(x0 + b[0] for _, _, x0, b in placed)
    max_x = max(x0 + b[2] for _, _, x0, b in placed)
    min_y = min(b[1] for *_, b in placed)
    max_y = max(b[3] for *_, b in placed)
    width, height = round(max_x - min_x), round(max_y - min_y)

    paths = {}
    for role, name, x0, _ in placed:
        pen = SVGPathPen(glyphs, ntos=lambda v: f"{v:.0f}")
        # Font units are y-up; SVG is y-down. Crop to the ink box.
        glyphs[name].draw(TransformPen(pen, (1, 0, 0, -1, x0 - min_x, max_y)))
        paths[role] = pen.getCommands()

    ts = ROOT / "apps/web/src/components/logomark.ts"
    ts.write_text(
        "/**\n"
        " * ∅·Δ logomark outlines, generated by scripts/convert-logomark.py.\n"
        f" * Source: Noto Sans Math {version} (SIL OFL 1.1, see logomark-OFL.txt).\n"
        " * Do not edit by hand; rerun the script.\n"
        " */\n"
        f"export const LOGOMARK_VIEWBOX = \"0 0 {width} {height}\";\n"
        f"export const LOGOMARK_RATIO = {width / height:.4f};\n"
        "export const LOGOMARK_PATHS = {\n"
        + "".join(f'\t{role}: "{d}",\n' for role, d in paths.items())
        + "} as const;\n"
    )

    # Square favicon: mark centred on the void background with 6% padding.
    side = width * 1.12
    oy = (side - height) / 2
    ox = width * 0.06
    favicon = ROOT / "apps/web/public/favicon.svg"
    favicon.write_text(
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {side:.0f} {side:.0f}">\n'
        "\t<title>Void Drift</title>\n"
        f'\t<rect width="{side:.0f}" height="{side:.0f}" rx="{side * 0.16:.0f}" fill="{FAVICON_BG}"/>\n'
        f'\t<g transform="translate({ox:.0f} {oy:.0f})" fill="{FAVICON_FG}">\n'
        + "".join(f'\t\t<path d="{d}"/>\n' for d in paths.values())
        + "\t</g>\n</svg>\n"
    )
    subprocess.run(["pnpm", "exec", "biome", "format", "--write", str(ts), str(favicon)], cwd=ROOT, check=True)
    print(f"viewBox 0 0 {width} {height}; wrote {ts.relative_to(ROOT)}, {favicon.relative_to(ROOT)}")


if __name__ == "__main__":
    convert(sys.argv[1])
