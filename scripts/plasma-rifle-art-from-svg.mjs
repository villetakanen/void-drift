// Derive static path geometry and conservative bounds from the unlit master.
// Run: node scripts/plasma-rifle-art-from-svg.mjs [--check]
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { chromium } from "@playwright/test";

const source = "packages/mode-a/src/lib/art/weapons/plasma-rifle.svg";
const target = "packages/mode-a/src/lib/plasma-rifle-paths.ts";
const browser = await chromium.launch({ headless: true });
try {
  const page = await browser.newPage();
  await page.setContent(readFileSync(source, "utf8"));
  const art = await page.locator("#rifle").evaluate((root) => {
    const svg = root.ownerSVGElement;
    const frame = svg.getCTM().inverse();
    return [...root.querySelectorAll("path, rect")].map((el) => {
      const transform = frame.multiply(el.getCTM());
      const matrix = [
        transform.a,
        transform.b,
        transform.c,
        transform.d,
        transform.e,
        transform.f,
      ];
      const box = el.getBBox();
      const path =
        el.tagName === "path"
          ? el.getAttribute("d")
          : `M${box.x} ${box.y}h${box.width}v${box.height}h${-box.width}Z`;
      const corners = [
        [box.x, box.y],
        [box.x + box.width, box.y],
        [box.x + box.width, box.y + box.height],
        [box.x, box.y + box.height],
      ].map(([x, y]) => {
        const p = new DOMPoint(x, y).matrixTransform(transform);
        return [p.x, p.y];
      });
      return { path, fill: getComputedStyle(el).fill, matrix, corners };
    });
  });
  const points = art.flatMap((face) => face.corners);
  const bounds = {
    left: Math.min(...points.map(([x]) => x)),
    right: Math.max(...points.map(([x]) => x)),
    front: Math.min(...points.map(([, y]) => y)),
    rear: Math.max(...points.map(([, y]) => y)),
  };
  const paths = art.map(({ corners: _corners, ...face }) => face);
  const output = `// Generated by scripts/plasma-rifle-art-from-svg.mjs from ${source}.\n// Edit the SVG master and regenerate. Coordinates are nose-up, receiver-centred.\nexport const PLASMA_RIFLE_PATHS = ${JSON.stringify(paths, null, 2)} as const;\nexport const PLASMA_RIFLE_BOUNDS = ${JSON.stringify(bounds, null, 2)} as const;\n`;
  const formatted = execFileSync(
    "node_modules/.bin/biome",
    ["format", "--stdin-file-path", target],
    { input: output, encoding: "utf8" },
  );
  if (process.argv.includes("--check")) {
    if (readFileSync(target, "utf8") !== formatted)
      throw new Error("Plasma rifle artefact differs from master");
  } else writeFileSync(target, formatted);
} finally {
  await browser.close();
}
