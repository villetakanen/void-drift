import type { GameObject } from "@void-drift/core";
import { Vec2 } from "@void-drift/core";
import { applyBuildEngines, buildDrain, engineImpulse } from "./build-flight";
import type { AssembledIonSettings } from "./schemas/ion";
import {
  buildStats,
  LIFE_SUPPORT_DRAIN,
  type Loadout,
  PARTS,
} from "./schemas/loadout";

type Command = { leftThruster: boolean; rightThruster: boolean; fire: false };
type Entry = Readonly<{
  dx: number;
  dy: number;
  heading: number;
  spin: number;
  energy: number;
}>;
export type ScoutFlightProfile = Readonly<{
  stats: ReturnType<typeof buildStats>;
  speedLimit: number;
  spinBins: readonly number[];
  entries: readonly (readonly Entry[])[];
}>;

const COMMANDS: readonly Command[] = Object.freeze([
  Object.freeze({ leftThruster: false, rightThruster: false, fire: false }),
  Object.freeze({ leftThruster: true, rightThruster: false, fire: false }),
  Object.freeze({ leftThruster: false, rightThruster: true, fire: false }),
  Object.freeze({ leftThruster: true, rightThruster: true, fire: false }),
]);
// Simulations own their ion settings. Equal fittings in the same run share a compiled table.
const profiles = new WeakMap<
  AssembledIonSettings,
  Map<string, ScoutFlightProfile>
>();
const resolved = new WeakMap<
  Loadout,
  { ion: AssembledIonSettings; profile: ScoutFlightProfile }
>();
const SAMPLE_DT = 1 / 240;
const TABLE_STEP = 0.1;
const TABLE_SUBSTEPS = Math.round(TABLE_STEP / SAMPLE_DT);

/** Immutable local body-frame dynamics, generated by production engine code. */
export function scoutFlightProfile(
  loadout: Loadout,
  ion: AssembledIonSettings,
): ScoutFlightProfile {
  const known = resolved.get(loadout);
  if (known?.ion === ion) return known.profile;
  const key = JSON.stringify(loadout);
  let catalogue = profiles.get(ion);
  if (!catalogue) {
    catalogue = new Map();
    profiles.set(ion, catalogue);
  }
  const previous = catalogue.get(key);
  if (previous) {
    resolved.set(loadout, { ion, profile: previous });
    return previous;
  }
  const stats = buildStats(loadout);
  const maxSpin = (ion.maxTurn * Math.PI) / 180;
  const spinBins = Object.freeze(
    Array.from({ length: 9 }, (_, i) => -maxSpin + (2 * maxSpin * i) / 8),
  );
  const entries = COMMANDS.map((command) =>
    Object.freeze(
      spinBins.map((initialSpin) => {
        const ship: GameObject = {
          pos: new Vec2(0, 0),
          vel: new Vec2(0, 0),
          acc: new Vec2(0, 0),
          rotation: 0,
          radius: 20,
        };
        const timers: Record<string, number> = {};
        const motion = { velocity: initialSpin };
        let dx = 0,
          dy = 0,
          energy = 0;
        for (let sub = 0; sub < TABLE_SUBSTEPS; sub++) {
          // Isolate the local engine impulse from the entry's initial translational velocity.
          ship.vel.set(0, 0);
          ship.acc.set(0, 0);
          const spinBefore = motion.velocity;
          const drain = buildDrain(
            loadout,
            command,
            spinBefore,
            SAMPLE_DT,
            ion,
            1,
            stats.mass,
          );
          energy -= (drain - LIFE_SUPPORT_DRAIN) * SAMPLE_DT;
          applyBuildEngines(
            ship,
            loadout,
            command,
            SAMPLE_DT,
            true,
            timers,
            1,
            motion,
            ion,
            PARTS,
            stats,
          );
          // The sampled ship started at heading zero. Its velocity is already in that starting frame.
          dx += ship.vel.x;
          dy += ship.vel.y;
        }
        return Object.freeze({
          dx,
          dy,
          heading: ship.rotation,
          spin: motion.velocity,
          energy,
        });
      }),
    ),
  );
  const profile = Object.freeze({
    stats: Object.freeze(stats),
    speedLimit: stats.poweredCruiseCeiling,
    spinBins,
    entries: Object.freeze(entries),
  });
  catalogue.set(key, profile);
  resolved.set(loadout, { ion, profile });
  return profile;
}

export function interpolateScoutEntry(
  profile: ScoutFlightProfile,
  commandIndex: number,
  spin: number,
): Entry {
  const bins = profile.spinBins;
  if (spin <= bins[0]) return profile.entries[commandIndex][0];
  const last = bins.length - 1;
  if (spin >= bins[last]) return profile.entries[commandIndex][last];
  let low = 0;
  while (low < last - 1 && bins[low + 1] < spin) low++;
  const a = profile.entries[commandIndex][low],
    b = profile.entries[commandIndex][low + 1];
  const f = (spin - bins[low]) / (bins[low + 1] - bins[low]);
  return {
    dx: a.dx + (b.dx - a.dx) * f,
    dy: a.dy + (b.dy - a.dy) * f,
    heading: a.heading + (b.heading - a.heading) * f,
    spin: a.spin + (b.spin - a.spin) * f,
    energy: a.energy + (b.energy - a.energy) * f,
  };
}

/** Apply a table's unconstrained body impulse using production speed taper. */
export function applyScoutTableImpulse(
  ship: GameObject,
  dx: number,
  dy: number,
  limit: number,
  dt = 1,
) {
  const magnitude = Math.hypot(dx, dy);
  if (magnitude > 1e-12)
    engineImpulse(
      ship,
      ship.rotation + Math.atan2(dy, dx),
      magnitude / dt,
      limit,
      dt,
    );
}

export {
  COMMANDS as SCOUT_PREDICTOR_COMMANDS,
  TABLE_STEP as SCOUT_PREDICTOR_STEP,
};
